import {
  calculateCombatPower,
  type ArenaProfile,
  type BattleEffectId,
  type BattleParticipantSnapshot,
} from '@rpg/game-engine';
export const TOWER_VERSION = 'permanent-v1';
const equipment = (id: BattleEffectId, power: number) => ({
  id: `tower-${id}`,
  name: (
    {
      'path-sword': 'Espada da Torre',
      'steadfast-shield': 'Escudo da Torre',
      'traveler-armor': 'Armadura da Torre',
      'pilgrim-boots': 'Botas da Torre',
      'prudence-amulet': 'Amuleto da Torre',
      'traveler-helmet': 'Elmo da Torre',
    } as const
  )[id],
  power,
  effectIds: [id],
});
function floor(
  index: number,
  name: string,
  difficulty: string,
  level: number,
  life: number,
  strength: number,
  defense: number,
  wisdom: number,
  arenaProfile: ArenaProfile,
  gear: [BattleEffectId, number][],
  strategy: string,
) {
  const base = {
    id: `tower-floor-${index}`,
    name,
    level,
    attributes: { life, strength, defense, wisdom },
    equipment: gear.map(([id, power]) => equipment(id, power)),
    arenaProfile,
  };
  const snapshot: BattleParticipantSnapshot = {
    ...base,
    combatPower: calculateCombatPower(base),
  };
  return {
    id: base.id,
    index,
    difficulty,
    strategy,
    snapshot,
    boss: index === 7,
  } as const;
}
